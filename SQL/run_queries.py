"""Run every query in SQL/queries.sql and save the results as Markdown.

Usage (from the repo root, after `python -m SQL.load_mysql`):
    python -m SQL.run_queries

Writes SQL/query_results.md (query text + result table for each query),
which is what the report quotes.
"""

import re
from datetime import datetime
from pathlib import Path

from sqlalchemy import create_engine, text
from sqlalchemy.engine import Engine

from api.config import settings

HERE = Path(__file__).resolve().parent
QUERIES_PATH = HERE / "queries.sql"
RESULTS_PATH = HERE / "query_results.md"


def parse_queries(sql: str) -> list[tuple[str, str]]:
    """Return [(title, query)] for each '-- @query: <title>' block."""
    blocks = re.split(r"^-- @query:\s*(.+)$", sql, flags=re.MULTILINE)
    # blocks = [preamble, title1, body1, title2, body2, ...]
    return [(title.strip(), body.strip().rstrip(";")) for title, body in zip(blocks[1::2], blocks[2::2])]


def markdown_table(columns: list[str], rows: list[tuple]) -> str:
    def fmt(value) -> str:
        if value is None:
            return "NULL"
        if isinstance(value, datetime):
            return value.strftime("%Y-%m-%d %H:%M:%S")
        if isinstance(value, float):
            return f"{value:g}"
        return str(value)

    lines = ["| " + " | ".join(columns) + " |", "|" + "---|" * len(columns)]
    lines += ["| " + " | ".join(fmt(v) for v in row) + " |" for row in rows]
    return "\n".join(lines)


def run_all(engine: Engine) -> str:
    sections = [
        "# SQL query results",
        "",
        f"Generated by `python -m SQL.run_queries` on {datetime.now():%Y-%m-%d %H:%M} "
        f"against `{engine.url.render_as_string(hide_password=True)}`.",
    ]
    queries = parse_queries(QUERIES_PATH.read_text(encoding="utf-8"))
    with engine.connect() as conn:
        for title, query in queries:
            result = conn.execute(text(query))
            columns, rows = list(result.keys()), result.fetchall()
            print(f"{title}: {len(rows)} rows")
            sections += [
                "", f"## {title}", "", "```sql", query + ";", "```", "",
                f"**Result ({len(rows)} rows):**", "", markdown_table(columns, rows),
            ]
    return "\n".join(sections) + "\n"


def main() -> None:
    engine = create_engine(settings.sqlalchemy_url)
    RESULTS_PATH.write_text(run_all(engine), encoding="utf-8")
    print(f"Saved {RESULTS_PATH}")


if __name__ == "__main__":
    main()
